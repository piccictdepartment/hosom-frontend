import type { Metadata } from 'next';
import { notFound, redirect } from 'next/navigation';
import { isRoleSlug, roles, sectionFor, type RoleSlug } from '@/lib/demo-data';
import { RoleOverview } from '@/components/role-overview';
import { StudentOverview } from '@/components/student-overview';
import { LecturerOverview } from '@/components/lecturer-overview';
import { StudentCourses } from '@/components/student-courses';
import { LecturerCourses } from '@/components/lecturer-courses';
import { LecturerMaterials } from '@/components/lecturer-materials';
import { LecturerLiveClasses, LecturerAttendance, LecturerStudents, LecturerProfile, LecturerPerformance, LecturerReports } from '@/components/lecturer-pages';
import { LecturerAssignments, LecturerQuizzes, LecturerMarking } from '@/components/lecturer-assessments';
import { LecturerCourseAnnouncements, LecturerAnnouncements, LecturerMessages } from '@/components/lecturer-communications';
import { LecturerMailer, LecturerAccountSecurity, LecturerPreferences } from '@/components/lecturer-account';
import { LearningContent } from '@/components/learning-content';
import { AccountContent } from '@/components/account-content';
import { ManagementContent } from '@/components/management-content';
import { WorkflowWorkspace } from '@/components/workflow-workspace';
import { StudentAssessments, StudentFinance, StudentResults } from '@/components/student-experience';
import { supportsLearningContent } from '@/lib/learning-routing';
import { supportsAccountContent } from '@/lib/account-routing';
import { supportsManagementContent } from '@/lib/management-routing';
import { supportsWorkflow } from '@/lib/workflow-routing';

type Params = Promise<{ role: string; section: string }>;
export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const { role, section } = await params;
  return { title: isRoleSlug(role) ? `${sectionFor(role, section) ?? 'Portal'} · ${roles[role].label}` : 'Portal' };
}
export default async function PortalSectionPage({ params }: { params: Params }) {
  const { role: rawRole, section: rawSection } = await params;
  if (!isRoleSlug(rawRole)) notFound();
  const role: RoleSlug = rawRole;
  if (role === 'student' && rawSection === 'finance') redirect('/portal/student/fees');
  const section = sectionFor(role, rawSection);
  if (!section) notFound();
  if (section === 'Overview') return role === 'student' ? <StudentOverview /> : role === 'lecturer' ? <LecturerOverview /> : <RoleOverview role={role} />;
  if (role === 'student' && section === 'My Courses') return <StudentCourses />;
  if (role === 'lecturer' && section === 'My Courses') return <LecturerCourses />;
  if (role === 'lecturer' && section === 'Materials') return <LecturerMaterials />;
  if (role === 'lecturer' && section === 'Live Classes') return <LecturerLiveClasses />;
  if (role === 'lecturer' && section === 'Attendance') return <LecturerAttendance />;
  if (role === 'lecturer' && section === 'Enrolled Students') return <LecturerStudents />;
  if (role === 'lecturer' && section === 'My Lecturer Profile') return <LecturerProfile />;
  if (role === 'lecturer' && section === 'Course Performance') return <LecturerPerformance />;
  if (role === 'lecturer' && ['Report Centre', 'Reports'].includes(section)) return <LecturerReports section={section} />;
  if (role === 'lecturer' && section === 'Assignments') return <LecturerAssignments />;
  if (role === 'lecturer' && section === 'Quizzes & Exams') return <LecturerQuizzes />;
  if (role === 'lecturer' && (section === 'Submissions' || section === 'Marks')) return <LecturerMarking section={section} />;
  if (role === 'lecturer' && section === 'Course Announcements') return <LecturerCourseAnnouncements />;
  if (role === 'lecturer' && section === 'Announcements') return <LecturerAnnouncements />;
  if (role === 'lecturer' && (section === 'Notifications' || section === 'Academic Updates' || section === 'Communications')) return <LecturerMessages section={section} />;
  if (role === 'lecturer' && section === 'Mailer') return <LecturerMailer />;
  if (role === 'lecturer' && section === 'Account Security') return <LecturerAccountSecurity />;
  if (role === 'lecturer' && section === 'Notification Preferences') return <LecturerPreferences />;
  if (role === 'student' && section === 'Assessments') return <StudentAssessments />;
  if (role === 'student' && section === 'Fees') return <StudentFinance />;
  if (role === 'student' && section === 'Results') return <StudentResults />;
  if (supportsLearningContent(role, section)) return <LearningContent role={role} section={section} />;
  if (supportsAccountContent(role, section)) return <AccountContent role={role} section={section} />;
  if (supportsManagementContent(role, section)) return <ManagementContent role={role} section={section} />;
  if (supportsWorkflow(role, section)) return <WorkflowWorkspace role={role} section={section} />;
  notFound();
}
